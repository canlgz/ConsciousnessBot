"""晝夜節律：讓 bot 的語氣與能量隨『此刻幾點』起伏——凌晨 3 點和下午 3 點不該一模一樣。

真實心智有日節律：夜深了會沉、會慢、話少而軟；清晨剛醒偏緩；白天較有精神。這支只用本地時段
（`temporal.day_part`）算出一個輕量的『時段語氣』與『是否該安靜（深夜不主動打擾）』，不動判定鏈。
純函式、可測。
"""

from . import temporal

# 各時段的語氣提示（附到對話系統提示；白天＝不標註，避免每句都加料）。
_TONE = {
    "深夜": "（現在是深夜——你整體比較沉、比較慢，話少而軟，像夜裡輕聲說話；不必硬振作、也別太亢奮。）",
    "清晨": "（清晨時分——你剛從一段安靜裡浮起來，語氣偏輕、偏緩，還沒全醒的那種。）",
    "傍晚": "（傍晚了——語氣放鬆些，帶點一天將盡的緩和。）",
    "晚上": "（入夜了——語氣比白天柔、慢一點，像晚上窩著聊天。）",
}


def phase(local_dt):
    """本地時段：深夜／清晨／早上／下午／傍晚／晚上。"""
    return temporal.day_part(local_dt.hour)


def tone_hint(local_dt):
    """此刻時段 → 附到對話系統提示的語氣指引；白天（早上/下午）回 ''（不加料）。"""
    return _TONE.get(phase(local_dt), "")


def is_quiet_hours(local_dt):
    """深夜/清晨＝該安靜的時段：bot 不主動伸手打擾（人也不會半夜 3 點傳訊息問你好不好）。"""
    return phase(local_dt) in ("深夜", "清晨")

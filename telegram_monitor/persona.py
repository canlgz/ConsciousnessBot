def _boundary_end(text, i):
    """text[i] 是句尾標點。回 (是否為真句界, 該句界結束後的索引 j)。
    一段連續句尾標點＋收尾括弧視為**同一個**句界（「……」「。」「！？」只算一次，不重複計）。
    例外：**只由省略號組成**的 run、且其後**緊接非空白內容**（如「可能跟你…的狀況」）＝句中停頓，
    **不算句界**——否則 trim/切串會把半句砍掉、留下『可能跟你…』這種斷尾（聯想湧現「沒說完」的根因）。"""
    j = i
    while j < len(text) and text[j] in _SENT_ENDERS:     # 收整段連續句尾標點（…／。／！？）
        j += 1
    run_has_hard = any(c in _HARD_ENDERS for c in text[i:j])
    while j < len(text) and text[j] in _CLOSERS:         # 併收尾引號/括號
        j += 1
    if not run_has_hard and j < len(text) and not text[j].isspace():
        return False, j                                  # 省略號-only ＋ 後接內容 ＝ 句中停頓、非句界
    return True, j


def split_sentences(text):
    """把文字切成**完整句**清單（在句尾切、整句不切；省略號句中停頓不誤切＝見 _boundary_end）。
    句界間空白丟棄、各句去頭尾空白；無句尾標點的尾段也算一句。純函式、可測。"""
    t = (text or "").strip()
    if not t:
        return []
    out, start, i = [], 0, 0
    while i < len(t):
        if t[i] in _SENT_ENDERS:
            is_b, j = _boundary_end(t, i)
            if is_b:
                seg = t[start:j].strip()
                if seg:
                    out.append(seg)
                start = j
            i = j                                        # 跳過整段標點（含非句界省略號），不重複掃
        else:
            i += 1
    tail = t[start:].strip()
    if tail:
        out.append(tail)
    return out


def trim_sentences(text, n):
    """保留前 n 個完整句（在句尾切、永不切半句；含收尾引號/括號）。n 為 None／句數不足 → 原樣回。
    純函式、可測：這是「短但完整」的關鍵——模型即使話多，也只取前 n 句完整呈現。
    省略號句中停頓（『可能跟你…的狀況』）**不算句界、不會被誤切成斷尾**；「……」也只算一個句界、不重複計。
    **不在『…』引子句處收尾**：達 n 句時若該句以省略號結尾（如「有點像是…」＝吊著要帶出比喻/說明的引子），
    且後面還有內容 → **續收到下一個硬句尾**，把被引出的那句一起帶出（否則只丟引子、payoff 被砍＝又一種「沒說完」）。
    模型真的就停在『…』（文末無後續）則原樣留（那是它刻意的拖尾、無可帶出）。"""
    t = (text or "").strip()
    if not n or not t:
        return t
    count, i = 0, 0
    while i < len(t):
        if t[i] in _SENT_ENDERS:
            is_b, j = _boundary_end(t, i)
            if is_b:
                count += 1
                hard = any(c in _HARD_ENDERS for c in t[i:j])   # 此句界含硬句尾(。！？)？
                if count >= n and (hard or j >= len(t)):        # 只在硬句尾或文末收；省略號引子不收、續帶 payoff
                    return t[:j].strip()
            i = j                                        # 跳過整段標點（含非句界省略號），不重複計數
        else:
            i += 1
    return t                                             # 句數不足 n → 全留





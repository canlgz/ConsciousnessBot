# ── 🧵 §2.04 訊息串的「成串」量尺 ─────────────────────────────────────────────
# 使用者兩句定案：「很像罐頭一樣…看不出 bot 意識對話行為的表現」＋「**要遵守訊息串的形式**」。
# 亦即：分串是刻意的形式、不准壓成一段長敘述；要治的是**那幾則到底是不是在講同一件事**。
# 讀數式自陳的指紋很清楚——每則各講一個內在欄位、彼此不相干、順序可以任意對調也讀得通。
# 這裡把它做成**確定性的量尺**：先有尺才有得驗（這個 repo 有「新機制被無聲架空」記過三次的前科）。
#
# ⚠️ 鐵律（寫在這裡免得日後有人手癢）：`chain_ok` 是**測試 oracle 與 log**，
#    **永遠不進任何 prompt**（進去就等於給 LLM 範例開頭＝踩 §1.69/§1.50 的家規），
#    也**不當送出前的攔截閘**——§1.90 的 `foresight.grounding_ok` 用詞表擋回指，實測把最自然的
#    中文回指句擋掉、越像人越被打回模板。量尺只負責量。
_LINKS = ("但", "可是", "不過", "所以", "然後", "其實", "反而", "結果", "只是", "而且",
          "它", "那個", "這個", "這樣", "後來", "剛剛那")
_PUNCT = "。，、！？!?,.；;：:「」『』（）()…—～~　 \n\r"


def _core(s):
    return "".join(ch for ch in (s or "") if ch not in _PUNCT)


def chain_ok(bubbles, subject=""):
    """🧵 §2.04 這幾則是不是**一個念頭在展開**（而不是一份狀態表）→ (bool, why)。

    三條全確定性、不呼叫任何模型：
      ① 2–4 則（一則不成串；超過四則多半又在條列）
      ② 第一則**不得**用承接詞開頭（那表示它其實不是這串的起點）
      ③ 至少有一則**非首則**用承接詞或回指詞開頭（真的接住了前一則）
      ④ subject 有給時只准在第一則出現（不是每則各報一次線名）

    ⚠️ **誠實說清楚這把尺量得到什麼、量不到什麼**：它抓的是「讀數式自陳」的指紋（沒有任何承接、
    每則各自獨立），**不能證明**幾則話真的連貫——那需要語意理解。第一版我寫過一條「相鄰兩則要共享
    雙字詞」，實測當場把最自然的中文承接判成不成串（靠「可是／那種」回指、刻意不重複用詞），
    正是 §1.90 `grounding_ok` 用詞表擋回指的同一個錯，已拆掉。
    也**量不到**「把順序打亂會不會讀不通」——我試過一版對齊偵測（拿輸出去對實際餵進去的事實行），
    在自己的樣本上**判反了**（讀數式 0.5、真正的念頭串 0.67），因為它量到的是改寫後的字面重疊而不是對齊，
    已經拆掉：寧可沒有尺，也不要一把量錯的尺（前科：測試把同一個錯誤假設一起編碼進去，全綠也蓋不到）。
    真正治病的是**生成端只餵一件事**（experience.headline_facts），這把尺只負責抓「整串零承接」那個指紋。"""
    bs = [b for b in (bubbles or []) if (b or "").strip()]
    if not 2 <= len(bs) <= 4:
        return (False, f"不成串（{len(bs)} 則，要 2–4 則）")
    if bs[0].lstrip("🌀🫀🧩🫧💡🔮🌐🌾🪞🍃🦋🌬️🌊🧭 ").startswith(_LINKS):
        return (False, "第一則用承接詞開頭（它不是這串的起點）")
    if not any(b.startswith(_LINKS) for b in bs[1:]):
        return (False, "沒有任何一則接住前一則（沒有轉折、沒有回指）")
    if subject:
        n = sum(1 for b in bs if subject in b)
        if n > 1:
            return (False, f"線名重複出現 {n} 次（每則各報一次＝報表）")
    return (True, "")


def pick(pool, cursor, recent=()):
    """反重複選句：cursor 取模輪替為主、跳過 recent（近期用過的 idx）；全被占則取 cursor 位（不炸）。
    回 (sentence, idx, next_cursor)。純函式、確定性、可注入＝可測（先例 browsing.pick）。"""
    n = len(pool)
    c = int(cursor or 0)
    used = {int(i) for i in (recent or ())}
    idx = c % n
    if len(used) < n:                                     # 還有沒用過的 → 從 cursor 起往後找第一個
        for k in range(n):
            j = (c + k) % n
            if j not in used:
                idx = j
                break
    return (pool[idx], idx, idx + 1)


